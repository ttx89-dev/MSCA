#!/usr/bin/env python3
"""Generate the committed documentation assets from LIVE MSCA verification.

Deterministic *for a given verification state*: the terminal cards embed
verbatim output of the real commands (`python -m msca --summary`,
`python -m msca.gates`), executed as subprocesses at generation time. If
gates regress, regeneration flips the card to FAIL — the asset cannot
silently lie. The banner itself is static geometry + titles.

Outputs (written under assets/ at the repository root):

  assets/banner.svg             README banner
  assets/terminal_summary.svg   the `--summary` output as a terminal card
  assets/terminal_gates.svg     the full `.gates` output (15 gates, the
                                self-test block, and the verdict) as a card

Run:

    python3 tools/make_doc_assets.py           # from the repository root
"""

from __future__ import annotations

import html
import os
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(REPO, "assets")

INK = "#101014"
CARD = "#0c0c10"
GREEN = "#7ec98f"
AMBER = "#E8A13C"
MUT = "#9AA0AC"
FAINT = "#6E7480"
MONO = "'DejaVu Sans Mono','JetBrains Mono',Consolas,monospace"


def run(cmd: list[str]) -> str:
    """Run a repo-verification command verbatim, fail loudly if it exits non-zero."""
    p = subprocess.run(cmd, cwd=REPO, capture_output=True, text=True, timeout=120)
    if p.returncode != 0:
        raise SystemExit(f"command failed ({p.returncode}): {' '.join(cmd)}\n{p.stdout}\n{p.stderr}")
    return p.stdout.rstrip("\n")


def card(title: str, lines: list[str], highlight: str = GREEN, height: int | None = None) -> str:
    """A terminal-style SVG card with a title bar and monospace lines."""
    lh, pad = 17.5, 16
    n = max(1, len(lines))
    H = height or (44 + n * lh + pad)
    W = min(920, max(560, max(len(x) for x in lines) * 8.9 + pad * 2 - 8))
    body = []
    for i, ln in enumerate(lines):
        color = highlight if "PASS" in ln or "MATCH" in ln or "NONE" in ln else (
            AMBER if ln.strip().startswith(("R1", "D5")) else "#cfd3da")
        body.append(
            f'<text x="{pad}" y="{40 + (i + 1) * lh:.1f}" xml:space="preserve" '
            f'font-family="{MONO}" font-size="12.4" fill="{color}">{html.escape(ln)}</text>'
        )
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="{W:.0f}" height="{H}" viewBox="0 0 {W:.0f} {H}" role="img" aria-label="{html.escape(title)}">
  <!-- generated by tools/make_doc_assets.py from live command output; regenerate with: python3 tools/make_doc_assets.py -->
  <rect width="{W:.0f}" height="{H:.0f}" rx="12" fill="{CARD}" stroke="#2c2a33" stroke-width="1"/>
  <circle cx="20" cy="20" r="5" fill="#e0574a"/><circle cx="38" cy="20" r="5" fill="#dfb03c"/><circle cx="56" cy="20" r="5" fill="#57b360"/>
  <text x="{W / 2:.0f}" y="24" text-anchor="middle" font-family="{MONO}" font-size="11" fill="{FAINT}">{html.escape(title)}</text>
  {"".join(body)}
</svg>
'''


def main() -> int:
    if not os.path.isdir(ASSETS):
        os.makedirs(ASSETS)

    summary = run([sys.executable, "-m", "msca", "--summary"]).splitlines()
    gates = run([sys.executable, "-m", "msca.gates"]).splitlines()
    gates_body = gates[1:]  # everything below the "MSCA gates" banner line:
                            # 15 gate rows, then the self-test block and verdict

    banner = f'''<svg xmlns="http://www.w3.org/2000/svg" width="880" height="240" viewBox="0 0 880 240" role="img" aria-label="MSCA banner">
  <!-- generated by tools/make_doc_assets.py; deterministic geometry -->
  <defs>
    <pattern id="rows" width="12" height="12" patternUnits="userSpaceOnUse">
      <rect width="12" height="12" fill="#111014"/>
      <rect y="11" width="12" height="1" fill="#221f27"/>
    </pattern>
  </defs>
  <rect width="880" height="240" rx="14" fill="url(#rows)"/>
  <rect x="1" y="1" width="878" height="238" rx="13" fill="none" stroke="#3a3842" stroke-width="1"/>
  <rect x="40" y="54" width="10" height="132" fill="{AMBER}" opacity="0.85"/>
  <rect x="58" y="54" width="10" height="34" fill="{GREEN}" opacity="0.75"/>
  <rect x="58" y="96" width="10" height="90" fill="#26221e"/>
  <text x="100" y="102" font-family="{MONO}" font-size="58" font-weight="700" fill="#E8E8EC" letter-spacing="2">MSCA</text>
  <text x="102" y="132" font-family="{MONO}" font-size="18" fill="#CFC9BF">Maximum Semantic Capacity Archive</text>
  <text x="102" y="158" font-family="{MONO}" font-size="13" fill="{MUT}">tiered agent memory: resident spine + phase-tagged loads, under a measured budget</text>
  <text x="842" y="216" text-anchor="end" font-family="{MONO}" font-size="11" fill="{FAINT}">15/15 gates &#183; 621 resident tok (p50k_base, measured) &#183; self_test=pass</text>
</svg>
'''
    outs = {
        "banner.svg": banner,
        "terminal_summary.svg": card("$ python -m msca --summary", summary),
        "terminal_gates.svg": card("$ python -m msca.gates", gates_body),
    }
    for name, svg in outs.items():
        path = os.path.join(ASSETS, name)
        with open(path, "w", encoding="utf-8") as f:
            f.write(svg)
        print(f"wrote   : assets/{name}  ({os.path.getsize(path)} bytes)")
    print(f"source  : live runs of 'python -m msca --summary' + 'python -m msca.gates' "
          f"({len(summary)} summary lines, {len(gates_body)} gate lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
